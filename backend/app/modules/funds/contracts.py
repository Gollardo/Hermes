def projection_funds(session: Session) -> list[FundResponse]:
    """Read active funds inside a caller-owned repeatable-read transaction."""
    return list_funds(session, include_archived=False, shared_lock=False)


def create_fund_definition(
    session: Session,
    *,
    name: str,
    description: str | None,
    percentage: Decimal,
    target_amount: Decimal | None,
) -> UUID:
    """Create a Funds-owned definition without exposing its private model."""
    return create_fund(
        session,
        name=name,
        description=description,
        percentage=percentage,
        target_amount=target_amount,
    ).id


def fund_response(session: Session, fund_id: UUID) -> FundResponse:
    return get_fund_response(session, fund_id)


